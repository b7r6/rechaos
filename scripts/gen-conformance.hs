-- Lean term rendering (faithful to lean/Rechaos/Types.lean field names)
-- ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

leanStr :: Text -> String
leanStr t = show (T.unpack t)

leanNat :: Natural -> String
leanNat = show

leanU64 :: Word64 -> String
leanU64 = printf "(0x%016x : UInt64)"

leanBool :: Bool -> String
leanBool True = "true"
leanBool False = "false"

leanOptNat :: Maybe Natural -> String
leanOptNat Nothing = "none"
leanOptNat (Just n) = "(some " ++ leanNat n ++ ")"

leanDirection :: Direction -> String
leanDirection Request = "Direction.request"
leanDirection Response = "Direction.response"

leanStatus :: Status -> String
leanStatus st =
  "Status." ++ case st of
    Cancelled -> "cancelled"
    InvalidArgument -> "invalidArgument"
    DeadlineExceeded -> "deadlineExceeded"
    NotFound -> "notFound"
    ResourceExhausted -> "resourceExhausted"
    FailedPrecondition -> "failedPrecondition"
    Internal -> "internal"
    Unavailable -> "unavailable"
    DataLoss -> "dataLoss"

leanFault :: Fault -> String
leanFault (Delay n) = "(Fault.delay " ++ leanNat n ++ ")"
leanFault (Abort st) = "(Fault.abort " ++ leanStatus st ++ ")"
leanFault (Dribble rate chunk) = "(Fault.dribble " ++ leanNat rate ++ " " ++ leanNat chunk ++ ")"
leanFault (Truncate keep) = "(Fault.truncate " ++ leanNat keep ++ ")"

leanOptFault :: Maybe Fault -> String
leanOptFault Nothing = "none"
leanOptFault (Just f) = "(some " ++ leanFault f ++ ")"

leanTarget :: Target -> String
leanTarget t =
  "{ method := "
    ++ leanStr (tMethod t)
    ++ ", direction := "
    ++ leanDirection (tDirection t)
    ++ ", occurrence := "
    ++ leanOptNat (tOccurrence t)
    ++ ", messageIndex := "
    ++ leanOptNat (tMessageIndex t)
    ++ ", minBlobBytes := "
    ++ leanOptNat (tMinBlobBytes t)
    ++ ", maxBlobBytes := "
    ++ leanOptNat (tMaxBlobBytes t)
    ++ ", afterMicros := "
    ++ leanOptNat (tAfterMicros t)
    ++ ", beforeMicros := "
    ++ leanOptNat (tBeforeMicros t)
    ++ " : Target }"

leanRule :: Rule -> String
leanRule r =
  "{ target := "
    ++ leanTarget (target r)
    ++ ", chancePpm := "
    ++ leanNat (chancePpm r)
    ++ ", fault := "
    ++ leanFault (fault r)
    ++ " : Rule }"

leanEvent :: Event -> String
leanEvent e =
  "{ method := "
    ++ leanStr (eMethod e)
    ++ ", occurrence := "
    ++ leanNat (eOccurrence e)
    ++ ", direction := "
    ++ leanDirection (eDirection e)
    ++ ", messageIndex := "
    ++ leanNat (eMessageIndex e)
    ++ ", blobBytes := "
    ++ leanOptNat (eBlobBytes e)
    ++ ", elapsedMicros := "
    ++ leanNat (eElapsedMicros e)
    ++ ", messageBytes := "
    ++ leanNat (eMessageBytes e)
    ++ ", payloadHash := "
    ++ leanStr (ePayloadHash e)
    ++ " : Event }"

leanList :: [String] -> String
leanList xs = "[" ++ intercalate ", " xs ++ "]"

-- A Decision as a Lean record, matching `Decision` in lean/Rechaos/Types.lean.
leanDecision :: Decision -> String
leanDecision d =
  "{ event := "
    ++ leanEvent (event d)
    ++ ", injection := "
    ++ leanOptFault (injection d)
    ++ " : Decision }"

-- A Timeline (List Decision) as a Lean list literal.
leanTimeline :: Timeline -> String
leanTimeline tl = leanList (map leanDecision tl)

-- A list of timelines (candidate set) as a Lean list literal.
leanTimelines :: [Timeline] -> String
leanTimelines tls = leanList (map leanTimeline tls)

leanPolicy :: Policy -> String
leanPolicy p =
  "{ seed := "
    ++ leanU64 (seed p)
    ++ ", rules := "
    ++ leanList (map leanRule (rules p))
    ++ " : Policy }"

-- A decision case rendered as a Lean tuple (policy, trace, expected injections).
-- We compare the *injected faults* (the scheduling outcome) rather than full
-- Decision records, since the events are exactly the trace by `schedule_events`.
leanDecisionCase :: (Policy, [Event], Timeline) -> String
leanDecisionCase (p, es, tl) =
  "( "
    ++ leanPolicy p
    ++ "\n  , "
    ++ leanList (map leanEvent es)
    ++ "\n  , "
    ++ leanList (map (leanOptFault . injection) tl)
    ++ " )"

-- ── oracle Lean rendering (faithful to lean/Rechaos/Oracle.lean) ──────────────

-- An Entry as a Lean term, matching the `Entry` constructors in Oracle.lean.
leanEntry :: Entry -> String
leanEntry (File h sz ex) =
  "(Entry.file " ++ leanStr h ++ " " ++ leanNat sz ++ " " ++ leanBool ex ++ ")"
leanEntry (Symlink t) = "(Entry.symlink " ++ leanStr t ++ ")"
leanEntry Directory = "Entry.directory"

leanOptEntry :: Maybe Entry -> String
leanOptEntry Nothing = "none"
leanOptEntry (Just e) = "(some " ++ leanEntry e ++ ")"

-- A sorted tree as a Lean `List (String × Entry)`, in ascending key order (the
-- order `Data.Map.toAscList` already guarantees), matching the Lean `Tree` port.
leanTree :: Tree -> String
leanTree t =
  leanList ["(" ++ leanStr k ++ ", " ++ leanEntry e ++ ")" | (k, e) <- M.toAscList t]

-- A Change as a Lean `{ path, before, after }` record.
leanChange :: Change -> String
leanChange (Change p x y) =
  "{ path := "
    ++ leanStr p
    ++ ", before := "
    ++ leanOptEntry x
    ++ ", after := "
    ++ leanOptEntry y
    ++ " : Change }"

-- A Verdict as a Lean term, matching the `Verdict` constructors in Oracle.lean.
leanVerdict :: Verdict -> String
leanVerdict Equivalent = "Verdict.equivalent"
leanVerdict (Diverged cs) = "(Verdict.diverged " ++ leanList (map leanChange cs) ++ ")"
leanVerdict Inconclusive = "Verdict.inconclusive"

-- An oracle case rendered as a Lean tuple (treeA, treeB, expected verdict).
leanOracleCase :: (Tree, Tree, Verdict) -> String
leanOracleCase (a, b, v) =
  "( "
    ++ leanTree a
    ++ "\n  , "
    ++ leanTree b
    ++ "\n  , "
    ++ leanVerdict v
    ++ " )"

-- ── minimizer Lean rendering (faithful to lean/Rechaos/Minimize.lean) ─────────

-- A candidate case rendered as a Lean tuple (timeline, expected candidate set).
leanMinimizeCase :: (Timeline, [Timeline]) -> String
leanMinimizeCase (tl, cs) =
  "( "
    ++ leanTimeline tl
    ++ "\n  , "
    ++ leanTimelines cs
    ++ " )"

-- A trajectory case rendered as a Lean tuple (timeline, threshold, converged best).
leanTrajectoryCase :: (Timeline, Natural, Timeline) -> String
leanTrajectoryCase (tl, threshold, result) =
  "( "
    ++ leanTimeline tl
    ++ "\n  , "
    ++ leanNat threshold
    ++ "\n  , "
    ++ leanTimeline result
    ++ " )"

