-- 4. output-tree oracle scope
-- ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

-- A scope of (treeA, treeB) build-output trees spanning: identity, additions,
-- deletions, hash/size/exec-bit changes, symlink-target changes, kind changes
-- (file <-> dir <-> symlink), empty-vs-nonempty, and multi-path diffs whose
-- changes must appear in ascending key order. The pairs are built as association
-- lists and loaded through `M.fromList`, so the reference `Data.Map` canonicalizes
-- key order exactly as the Lean sorted-list port expects.
oracleTreePairs :: [([(Text, Entry)], [(Text, Entry)])]
oracleTreePairs =
  [ -- identical empty trees -> Equivalent
    ([], [])
  , -- identical singletons -> Equivalent
    ([("a", File "h1" 10 False)], [("a", File "h1" 10 False)])
  , -- an addition on the right
    ([], [("a", File "h1" 10 False)])
  , -- a deletion on the right
    ([("a", File "h1" 10 False)], [])
  , -- content-hash change
    ([("a", File "h1" 10 False)], [("a", File "h2" 10 False)])
  , -- size change
    ([("a", File "h1" 10 False)], [("a", File "h1" 11 False)])
  , -- executable-bit change
    ([("a", File "h1" 10 False)], [("a", File "h1" 10 True)])
  , -- symlink-target change
    ([("a", Symlink "x")], [("a", Symlink "y")])
  , -- file -> directory kind change
    ([("a", File "h1" 10 False)], [("a", Directory)])
  , -- directory -> symlink kind change
    ([("a", Directory)], [("a", Symlink "t")])
  , -- file -> symlink kind change
    ([("a", File "h1" 10 False)], [("a", Symlink "t")])
  , -- multi-path identity -> Equivalent

    ( [("a", File "h1" 1 False), ("b", Directory), ("c", Symlink "t")]
    , [("a", File "h1" 1 False), ("b", Directory), ("c", Symlink "t")]
    )
  , -- several changes at once; diff must be ascending by key

    ( [("a", File "h1" 1 False), ("b", Directory), ("m", Symlink "x")]
    , [("a", File "h9" 1 False), ("c", File "h3" 2 True), ("m", Symlink "y")]
    )
  , -- an addition that sorts before an existing key
    ([("b", File "h1" 1 False)], [("a", Directory), ("b", File "h1" 1 False)])
  , -- an addition that sorts after an existing key
    ([("a", File "h1" 1 False)], [("a", File "h1" 1 False), ("z", Directory)])
  , -- disjoint key sets -> every path is a change
    ([("a", File "h1" 1 False)], [("b", File "h1" 1 False)])
  , -- a wholly nonoverlapping multi-key pair, exercising interleaved ordering

    ( [("a", Directory), ("c", Directory), ("e", Directory)]
    , [("b", Directory), ("d", Directory), ("f", Directory)]
    )
  , -- identical directories only
    ([("d1", Directory), ("d2", Directory)], [("d1", Directory), ("d2", Directory)])
  ]

-- Each oracle case: the two trees (as Data.Map, canonicalized) and the verdict the
-- reference `compareBuilds` renders on the two successful builds. Every expected
-- verdict is produced by the real Haskell oracle, so the corpus is
-- reference-generated by construction.
oracleCases :: [(Tree, Tree, Verdict)]
oracleCases =
  [ (a, b, compareBuilds (Built a) (Built b))
  | (as, bs) <- oracleTreePairs
  , let a = M.fromList as
  , let b = M.fromList bs
  ]

