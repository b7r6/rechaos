-- JSON golden rendering (compact one-row-per-line, machine-stable)
-- ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

jsonBool :: Bool -> String
jsonBool True = "true"
jsonBool False = "false"

-- A gate row as a compact JSON array: [seed, chancePpm, fires].
gateJsonRow :: (Word64, Natural, Bool) -> String
gateJsonRow (s, c, f) = "[" ++ show s ++ "," ++ show c ++ "," ++ jsonBool f ++ "]"

-- ── oracle JSON golden rendering (compact one-row-per-line) ───────────────────

-- An Entry as compact JSON, tagged by kind.
jsonEntry :: Entry -> String
jsonEntry (File h sz ex) =
  "{\"kind\":\"file\",\"hash\":"
    ++ show (T.unpack h)
    ++ ",\"size\":"
    ++ show sz
    ++ ",\"exec\":"
    ++ jsonBool ex
    ++ "}"
jsonEntry (Symlink t) = "{\"kind\":\"symlink\",\"target\":" ++ show (T.unpack t) ++ "}"
jsonEntry Directory = "{\"kind\":\"directory\"}"

jsonOptEntry :: Maybe Entry -> String
jsonOptEntry Nothing = "null"
jsonOptEntry (Just e) = jsonEntry e

-- A tree as a JSON array of [path, entry] pairs in ascending key order.
jsonTree :: Tree -> String
jsonTree t =
  "["
    ++ intercalate "," ["[" ++ show (T.unpack k) ++ "," ++ jsonEntry e ++ "]" | (k, e) <- M.toAscList t]
    ++ "]"

-- A verdict as compact JSON: a tagged object carrying the canonical changes when
-- diverged, so the golden fully captures the reference oracle's output.
jsonVerdict :: Verdict -> String
jsonVerdict Equivalent = "{\"verdict\":\"equivalent\"}"
jsonVerdict Inconclusive = "{\"verdict\":\"inconclusive\"}"
jsonVerdict (Diverged cs) =
  "{\"verdict\":\"diverged\",\"changes\":["
    ++ intercalate "," (map jsonChange cs)
    ++ "]}"
 where
  jsonChange (Change p x y) =
    "{\"path\":"
      ++ show (T.unpack p)
      ++ ",\"before\":"
      ++ jsonOptEntry x
      ++ ",\"after\":"
      ++ jsonOptEntry y
      ++ "}"

-- An oracle case as one compact JSON line: both trees and the reference verdict.
oracleJsonRow :: (Tree, Tree, Verdict) -> String
oracleJsonRow (a, b, v) =
  "{\"a\":" ++ jsonTree a ++ ",\"b\":" ++ jsonTree b ++ ",\"verdict\":" ++ jsonVerdict v ++ "}"

-- ── minimizer JSON golden rendering (compact one-row-per-line) ────────────────

-- A fault as compact JSON, tagged by constructor (shared shape with decisions).
jsonMinFault :: Maybe Fault -> String
jsonMinFault Nothing = "null"
jsonMinFault (Just (Delay n)) = "{\"delay\":" ++ show n ++ "}"
jsonMinFault (Just (Abort st)) = "{\"abort\":" ++ show (statusCode st) ++ "}"
jsonMinFault (Just (Dribble rate chunk)) =
  "{\"dribble\":[" ++ show rate ++ "," ++ show chunk ++ "]}"
jsonMinFault (Just (Truncate keep)) = "{\"truncate\":" ++ show keep ++ "}"

-- A timeline as a JSON array of per-decision [occurrence, injection] pairs. The
-- occurrence pins which anchor event each decision sits on, so the golden captures
-- both the surviving event identities and their (possibly weakened) faults.
jsonMinTimeline :: Timeline -> String
jsonMinTimeline tl =
  "["
    ++ intercalate
      ","
      ["[" ++ show (eOccurrence (event d)) ++ "," ++ jsonMinFault (injection d) ++ "]" | d <- tl]
    ++ "]"

-- A candidate case as one compact JSON line: the input timeline and the reference
-- candidate set it generates.
minimizeJsonRow :: (Timeline, [Timeline]) -> String
minimizeJsonRow (tl, cs) =
  "{\"input\":"
    ++ jsonMinTimeline tl
    ++ ",\"candidates\":["
    ++ intercalate "," (map jsonMinTimeline cs)
    ++ "]}"

-- A trajectory case as one compact JSON line: the input timeline, the oracle's
-- Delay threshold, and the converged best the reference minimizer shrinks to.
trajectoryJsonRow :: (Timeline, Natural, Timeline) -> String
trajectoryJsonRow (tl, threshold, result) =
  "{\"input\":"
    ++ jsonMinTimeline tl
    ++ ",\"threshold\":"
    ++ show threshold
    ++ ",\"best\":"
    ++ jsonMinTimeline result
    ++ "}"

