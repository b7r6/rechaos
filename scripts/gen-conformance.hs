-- 5. minimizer scope
-- ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

-- A fixed anchor event the minimizer timelines hang their faults on. messageBytes
-- is set so the intensity caps (Truncate toward messageBytes, Dribble toward
-- messageBytes * microsPerSecond) are nontrivial and the weaker-step arithmetic is
-- exercised on both sides of its bounds.
minimizeEvent :: Natural -> Event
minimizeEvent i = Event "google.bytestream.ByteStream/Read" i Response 1 (Just 100) (i * 10) 64 "h"

-- A decision carrying an (optional) injected fault at the i-th anchor event.
minimizeDecision :: Natural -> Maybe Fault -> Decision
minimizeDecision i = Decision (minimizeEvent i)

-- A scope of timelines spanning: empty, single faults of every intensity-bearing
-- constructor (Delay, Truncate, Dribble) at interior and boundary values, Abort
-- (no weaker form), a mixed multi-fault timeline, and timelines with passthrough
-- (Nothing) decisions interleaved — so `candidates` is probed on deletion halving,
-- singleton deletion, and every `weaker` branch, including the no-op caps.
minimizeScope :: [Timeline]
minimizeScope =
  [ []
  , [minimizeDecision 1 (Just (Delay 8))]
  , [minimizeDecision 1 (Just (Delay 1))]
  , [minimizeDecision 1 (Just (Delay 0))]
  , [minimizeDecision 1 (Just (Truncate 0))]
  , [minimizeDecision 1 (Just (Truncate 63))]
  , [minimizeDecision 1 (Just (Truncate 64))]
  , [minimizeDecision 1 (Just (Dribble 1 16))]
  , [minimizeDecision 1 (Just (Dribble (64 * microsPerSecond) 16))]
  , [minimizeDecision 1 (Just (Abort Internal))]
  , [minimizeDecision 1 (Just (Delay 4)), minimizeDecision 2 (Just (Truncate 10))]
  ,
    [ minimizeDecision 1 (Just (Delay 4))
    , minimizeDecision 2 Nothing
    , minimizeDecision 3 (Just (Dribble 2 8))
    ]
  ,
    [ minimizeDecision 1 (Just (Delay 2))
    , minimizeDecision 2 (Just (Truncate 60))
    , minimizeDecision 3 (Just (Abort NotFound))
    , minimizeDecision 4 (Just (Delay 16))
    ]
  ]

-- Each candidate case: the input timeline and the reference `candidates` set it
-- produces. Every expected candidate list is produced by the real Haskell
-- minimizer, so the corpus is reference-generated by construction.
minimizeCases :: [(Timeline, [Timeline])]
minimizeCases = [(tl, Min.candidates tl) | tl <- minimizeScope]

-- A deterministic oracle for the acceptance-trajectory corpus: a candidate
-- Triggers iff it still retains a Delay of at least `threshold` micros somewhere.
-- This is a total, pure predicate, so the trajectory is fully reproducible; it
-- drives `start`/`candidate`/`observe` to a converged `best`.
triggersAtLeast :: Natural -> Timeline -> Min.Verdict
triggersAtLeast threshold tl =
  if any delayAtLeast tl then Min.Triggers else Min.DoesNotTrigger
 where
  delayAtLeast d = case injection d of
    Just (Delay n) -> n >= threshold
    _ -> False

-- Drive the acceptance state machine to convergence under a deterministic oracle,
-- bounded by explicit fuel (the corpus scope needs far less than the cap). Returns
-- the converged `best` timeline. Uses only the reference `start`/`candidate`/
-- `observe`, so the trajectory is reference-generated end to end.
runShrink :: (Timeline -> Min.Verdict) -> Int -> Min.ShrinkState -> Timeline
runShrink _ 0 st = Min.best st
runShrink oracle fuel st = case Min.candidate st of
  Nothing -> Min.best st
  Just c -> runShrink oracle (fuel - 1) (Min.observe (oracle c) st)

-- Each trajectory case: a failing timeline, the Delay threshold the oracle keys
-- on, and the converged `best` the reference minimizer shrinks it to. The Lean
-- port must reproduce the same converged timeline.
minimizeTrajectoryCases :: [(Timeline, Natural, Timeline)]
minimizeTrajectoryCases =
  [ (tl, threshold, runShrink (triggersAtLeast threshold) 500 (Min.start tl))
  | (tl, threshold) <- trajectorySeeds
  ]
 where
  trajectorySeeds =
    [ ([minimizeDecision 1 (Just (Delay 8))], 1)
    , ([minimizeDecision 1 (Just (Delay 8)), minimizeDecision 2 (Just (Truncate 10))], 1)
    ,
      (
        [ minimizeDecision 1 (Just (Delay 4))
        , minimizeDecision 2 (Just (Abort NotFound))
        , minimizeDecision 3 (Just (Delay 16))
        ]
      , 4
      )
    ,
      (
        [ minimizeDecision 1 (Just (Truncate 0))
        , minimizeDecision 2 (Just (Delay 10))
        ]
      , 3
      )
    ]

